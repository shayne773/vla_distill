"""Render results/phase1/SUMMARY.md from the raw JSON results of every evaluated model.

    uv run scripts/phase1/make_summary.py --models teacher_l18 student_l06_init
"""

import dataclasses
import json
import math
import pathlib

import tyro


@dataclasses.dataclass
class Args:
    models: list[str] = dataclasses.field(default_factory=lambda: ["teacher_l18", "student_l06_init"])
    root: str = "results/phase1"
    reference: str = "teacher_l18"


SUITES = ("libero_spatial", "libero_object", "libero_goal", "libero_10")


def _load(path: pathlib.Path):
    return json.loads(path.read_text()) if path.exists() else None


def _pct(r):
    if r is None or r["n"] == 0:
        return "n/a"
    lo, hi = r["ci95"]
    return f"{100 * r['rate']:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]"


def _m(x):
    return f"{x / 1e6:,.0f}M"


def _paired(ref_dir: pathlib.Path, dir_: pathlib.Path):
    """Paired comparison on identical (suite, task, init state): discordant counts + exact McNemar p-value."""
    def load(d):
        out = {}
        for f in (d / "episodes").glob("*.json"):
            for e in json.loads(f.read_text())["episodes"]:
                out[(e["suite"], e["task_id"], e["init_state_idx"])] = e["success"]
        return out

    a, b = load(ref_dir), load(dir_)
    keys = sorted(set(a) & set(b))
    only_ref = sum(1 for k in keys if a[k] and not b[k])
    only_new = sum(1 for k in keys if b[k] and not a[k])
    n = only_ref + only_new
    p = min(1.0, 2 * sum(math.comb(n, i) for i in range(0, min(only_ref, only_new) + 1)) / 2**n) if n else 1.0
    return {"pairs": len(keys), "ref_only_success": only_ref, "model_only_success": only_new, "mcnemar_exact_p": p}


def main(args: Args) -> None:
    root = pathlib.Path(args.root)
    lines = ["# Phase 1 results (laptop, RTX 5080 Laptop 16 GB)", ""]
    lines += [
        "Generated by `scripts/phase1/make_summary.py` from the raw JSON under `results/phase1/`.",
        "Success rates are % with Wilson 95% CIs; 10 trials x 10 tasks per suite (init states 0-9, seed 7),",
        "identical for every model (paired). Latency = one action chunk (10 actions, 10 denoising steps), batch 1,",
        "bf16, torch.compile, CUDA-synchronized, 200 timed calls after 20 warm-up calls.",
        "",
        "## LIBERO success rate",
        "",
        "| Model | " + " | ".join(SUITES) + " | Overall |",
        "|---|" + "---|" * (len(SUITES) + 1),
    ]
    summaries = {}
    for m in args.models:
        s = _load(root / "libero" / m / "summary.json")
        summaries[m] = s
        if s is None:
            lines.append(f"| {m} | " + " | ".join(["not run"] * (len(SUITES) + 1)) + " |")
            continue
        cells = [_pct(s["per_suite"].get(suite)) for suite in SUITES]
        lines.append(f"| {m} | " + " | ".join(cells) + f" | {_pct(s['overall'])} |")
    ref_dir = root / "libero" / args.reference
    paired_rows = []
    for m in args.models:
        if m == args.reference or summaries.get(m) is None or summaries.get(args.reference) is None:
            continue
        pr = _paired(ref_dir, root / "libero" / m)
        paired_rows.append(
            f"| {m} vs {args.reference} | {pr['pairs']} | {pr['ref_only_success']} | {pr['model_only_success']} | "
            f"{pr['mcnemar_exact_p']:.2g} |"
        )
    if paired_rows:
        lines += [
            "",
            "Paired comparison (same init state, env seed and noise seeds per episode):",
            "",
            "| Comparison | Paired episodes | Teacher-only successes | Model-only successes | Exact McNemar p |",
            "|---|---|---|---|---|",
            *paired_rows,
        ]

    lines += [
        "",
        "## Speed, memory, size",
        "",
        "| Model | Layers (VLM / expert) | Latency p50 (ms) | p95 (ms) | Policy.infer p50 (ms) | Peak GPU mem, inference (GiB alloc / reserved) | Weights (GiB) |",
        "|---|---|---|---|---|---|---|",
    ]
    benches = {m: _load(root / "bench" / f"{m}.json") for m in args.models}
    for m, b in benches.items():
        if b is None:
            lines.append(f"| {m} | | not run | | | | |")
            continue
        g = b["gpu_memory_bytes"]
        lines.append(
            f"| {m} | {b['gemma_depth']} / {b['gemma_depth']} | {b['latency_ms']['p50']:.1f} | {b['latency_ms']['p95']:.1f} | "
            f"{b['policy_infer_e2e_ms']['p50']:.1f} | {g['peak_allocated_inference'] / 2**30:.2f} / "
            f"{g['peak_reserved_inference'] / 2**30:.2f} | {g['weights'] / 2**30:.2f} |"
        )
    lines += [
        "",
        "Parameter counts:",
        "",
        "| Model | Total | Vision encoder (SigLIP + projector) | VLM backbone layers | VLM token embedding (tied) | Action expert (+ projections) |",
        "|---|---|---|---|---|---|",
    ]
    for m, b in benches.items():
        if b is None:
            continue
        p = b["params"]
        lines.append(
            f"| {m} | {_m(p['total'])} | {_m(p['vision_encoder'])} | {_m(p['vlm_backbone_layers'])} | "
            f"{_m(p['vlm_token_embedding'])} | {_m(p['action_expert'])} |"
        )

    lines += [
        "",
        "## Offline action agreement (held-out frames, MSE vs teacher)",
        "",
        "| Model | Frames | Chunk MSE (mean [bootstrap 95% CI]) | First-action MSE | Gripper sign agreement | spatial | object | goal | libero_10 |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for m in args.models:
        a = _load(root / "action_agreement" / f"{m}.json")
        if a is None:
            lines.append(f"| {m} | not run | | | | | | | |")
            continue
        lo, hi = a["mse_chunk_ci95_bootstrap"]
        ps = a["per_suite_mse"]
        lines.append(
            f"| {m} | {a['num_frames']} | {a['mse_chunk_mean']:.4g} [{lo:.3g}, {hi:.3g}] | {a['mse_first_action_mean']:.4g} | "
            f"{100 * a['gripper_sign_agreement']:.1f}% | "
            + " | ".join(f"{ps.get(s, float('nan')):.3g}" for s in SUITES)
            + " |"
        )
    train = _load(root / "train_smoke" / "distill_smoke.json")
    if train is not None:
        lines += ["", "## Distillation training smoke test", "", "```json", json.dumps(train, indent=2), "```"]
    env = next((b["env"] for b in benches.values() if b), None)
    if env:
        lines += ["", "## Environment", "", "```json", json.dumps(env, indent=2), "```"]
    (root / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main(tyro.cli(Args))
